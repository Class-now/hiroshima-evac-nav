let current = "ja-easy";

export function setLang(code) {
  if (S[code]) current = code;
  const meta = LANGS.find((l) => l.code === current);
  document.documentElement.lang = meta.htmlLang;
  try { localStorage.setItem("lang", current); } catch (_) {}
}

export function getLang() {
  return current;
}

export function initialLang() {
  try {
    const saved = localStorage.getItem("lang");
    if (saved && S[saved]) return saved;
  } catch (_) {}
  const nav = (navigator.language || "").toLowerCase();
  if (nav.startsWith("zh")) return "zh";
  if (nav.startsWith("ko")) return "ko";
  if (nav.startsWith("ja")) return "ja-easy";
  return "en";
}

export function t(key, vars = {}) {
  const v = S[current][key] ?? S.en[key] ?? key;
  if (typeof v !== "string") return v;
  return v.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ""));
}
export const STRINGS = S;
